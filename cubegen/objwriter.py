"""Pure-Python OBJ/MTL writer.

Used by ``--no-blender`` for quick iteration and CI. Blender stays the
recommended exporter (FBX for Unity, previews, icons), but this keeps the
generator usable on machines without Blender. Pivots of moving parts are lost
in OBJ (it has no object transforms) - use FBX for the game.
"""

from __future__ import annotations

import os

from .asset import Asset
from .geometry import box_uvs
from .materials import MATERIALS, srgb_to_linear


def write_obj(asset: Asset, path: str, mtl_file: str, material_map=None) -> None:
    """Write ``asset`` as Y-up OBJ (same axis convention as Blender's exporter), one ``o`` per object."""
    lines = [
        "# generated by cubegen (Cube Escape model generator)",
        f"# type={asset.meta.get('type')} seed={asset.meta.get('seed')}",
        f"mtllib {mtl_file}",
    ]
    v_off = vt_off = vn_off = 0
    for obj in asset.meshes():
        mesh = obj.mesh
        lines.append(f"o {obj.name}")
        for x, y, z in mesh.verts:
            lines.append(f"v {x:.6f} {z:.6f} {-y:.6f}")
        uv_counts = []
        for fi, face in enumerate(mesh.faces):
            uvs = box_uvs(mesh.face_points(fi), mesh.face_normal(fi))
            uv_counts.append(len(uvs))
            lines += [f"vt {u:.6f} {v:.6f}" for u, v in uvs]
        for fi in range(len(mesh.faces)):
            nx, ny, nz = mesh.face_normal(fi)
            lines.append(f"vn {nx:.4f} {nz:.4f} {-ny:.4f}")
        lines.append("s off")
        current = None
        vt = vt_off + 1
        for fi, face in enumerate(mesh.faces):
            role = (material_map or {}).get(mesh.roles[fi], mesh.roles[fi])
            if role != current:
                current = role
                lines.append(f"usemtl {current}")
            refs = []
            for vi in face:
                refs.append(f"{vi + 1 + v_off}/{vt}/{fi + 1 + vn_off}")
                vt += 1
            lines.append("f " + " ".join(refs))
        v_off += len(mesh.verts)
        vt_off += sum(uv_counts)
        vn_off += len(mesh.faces)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")


def write_mtl(path: str, textures=None) -> None:
    """Material library with the Cube Escape materials (flat colours, emission for glow) and, if given,
    the textured ``MT_...`` materials (paths relative to the .mtl)."""
    base = os.path.dirname(os.path.abspath(path))
    lines = []
    for name, (color, smoothness, metallic, emission) in MATERIALS.items():
        r, g, b = (srgb_to_linear(c) for c in color)
        lines += [
            f"newmtl {name}",
            f"Kd {r:.4f} {g:.4f} {b:.4f}",
            "Ks 0.0 0.0 0.0",
            f"Ns {smoothness * 1000:.0f}",
            f"Pm {metallic:.2f}",
            f"Ke {r:.4f} {g:.4f} {b:.4f}" if emission else "Ke 0.0 0.0 0.0",
            "illum 2",
            "",
        ]
    for info in (textures or {}).values():
        rel = {k: os.path.relpath(v, base).replace(os.sep, "/") for k, v in info["paths"].items()}
        lines += [
            f"newmtl {info['name']}",
            "Kd 1.0 1.0 1.0",
            "Ks 0.0 0.0 0.0",
            f"Pm {info['metallic']:.2f}",
            f"map_Kd {rel['Albedo']}",
            f"map_Pr {rel['Roughness']}",
            f"norm {rel['Normal']}",
            "illum 2",
            "",
        ]
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
